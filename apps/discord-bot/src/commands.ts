/**
 * Slash commands under /guardian.
 *
 * The command tree is plain data in the shape Discord's REST API takes, so this
 * module has no runtime dependency on discord.js and `handleCommand` runs in a
 * test with nothing but fakes. bot.ts turns an interaction into a
 * `CommandInput` and a `CommandReply` back into an ephemeral response.
 *
 * Three rules from DESIGN.md 8 and CLAUDE.md shape every branch here. Replies
 * are ephemeral, always: nothing the bot says about a conversation goes into a
 * public channel. The owner is the reporter of record, so `export` hands them a
 * draft and never files anything. And every reply passes through the
 * accusation guard, because a false accusation generated by Guardian is
 * Guardian's own speech (rule 5).
 */

export const COMMAND_NAME = "guardian";

export const SUBCOMMANDS = [
  "setup",
  "role",
  "trusted",
  "timeout",
  "exclude",
  "status",
  "export",
  "verify",
] as const;
export type Subcommand = (typeof SUBCOMMANDS)[number];

/**
 * Anyone in the server may run status, but what it answers depends on the
 * caller. A member gets the overt disclosure rule 3 requires: Guardian is here
 * and whether it is scoring. Only Manage Server sees the settings, and in
 * particular the list of channels Guardian does not read, because that list is
 * a map of where it is blind.
 */
export const OPEN_SUBCOMMANDS: readonly Subcommand[] = ["status"];

